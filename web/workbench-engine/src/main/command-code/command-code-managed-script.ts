import {
  buildPosixHookEnvironmentIdentityMigration,
  buildWindowsHookEndpointRefresh,
  buildWindowsHookEnvironmentIdentityMigration
} from '../agent-hooks/hook-environment-identity-prelude'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines,
  buildWindowsHookStdinDrainEpilogue
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      ...buildWindowsHookEnvironmentIdentityMigration(),
      'if not "%ZKYQ_AGENT_HOOK_PORT%"=="" goto :zkyq_hook_endpoint_ready',
      ...buildWindowsHookEndpointRefresh(),
      ':zkyq_hook_endpoint_ready',
      'if "%ZKYQ_AGENT_HOOK_TOKEN%"=="" if defined ZKYQ_AGENT_HOOK_ENDPOINT call :maybeSourceEndpoint "%ZKYQ_AGENT_HOOK_ENDPOINT%"',
      'if "%ZKYQ_AGENT_HOOK_TOKEN%"=="" if not "%ZKYQ_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if defined ZKYQ_USER_DATA_PATH if exist "%ZKYQ_USER_DATA_PATH%\\agent-hooks" for /r "%ZKYQ_USER_DATA_PATH%\\agent-hooks" %%F in (endpoint-v2.cmd endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\orca-dev\\agent-hooks" for /r "%APPDATA%\\orca-dev\\agent-hooks" %%F in (endpoint-v2.cmd endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'if "%ZKYQ_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\orca\\agent-hooks" for /r "%APPDATA%\\orca\\agent-hooks" %%F in (endpoint-v2.cmd endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%ZKYQ_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set ZKYQ_AGENT_HOOK_PORT=" /c:"set ORCA_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%ZKYQ_AGENT_HOOK_PORT%" call :readMatchingEndpoint "%~1"',
      'exit /b 0',
      ':readMatchingEndpoint',
      'set "ZKYQ_AGENT_HOOK_ENDPOINT=%~1"',
      ...buildWindowsHookEndpointRefresh(),
      'exit /b 0',
      ...buildWindowsHookStdinDrainEpilogue(),
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookEnvironmentIdentityMigration(),
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__orca_read_ancestor_var() {',
    '  __orca_name="$1"',
    '  __orca_names="(${__orca_name}|ORCA_${__orca_name#ZKYQ_})"',
    '  __orca_pid="${PPID:-}"',
    '  while [ -n "$__orca_pid" ] && [ "$__orca_pid" != "0" ] && [ "$__orca_pid" != "1" ]; do',
    '    __orca_value=""',
    '    if [ -r "/proc/$__orca_pid/environ" ]; then',
    '      __orca_value=$(tr "\\000" "\\n" < "/proc/$__orca_pid/environ" 2>/dev/null | sed -n -E "s/^${__orca_names}=//p" | sort -u)',
    '    fi',
    '    if [ -z "$__orca_value" ]; then',
    '      __orca_value=$(ps eww -p "$__orca_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n -E "s/^${__orca_names}=//p" | sort -u)',
    '    fi',
    '    if [ -n "$__orca_value" ]; then',
    '      case "$__orca_value" in *"\n"*) return 2 ;; esac',
    '      printf "%s\\n" "$__orca_value"',
    '      return 0',
    '    fi',
    '    __orca_pid=$(ps -o ppid= -p "$__orca_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__orca_fill_from_ancestor() {',
    '  __orca_name="$1"',
    '  case "$__orca_name" in',
    '    ZKYQ_AGENT_HOOK_ENDPOINT) [ -z "${ZKYQ_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    ZKYQ_AGENT_HOOK_PORT) [ -z "${ZKYQ_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    ZKYQ_AGENT_HOOK_TOKEN) [ -z "${ZKYQ_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    ZKYQ_AGENT_HOOK_ENV) [ -z "${ZKYQ_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    ZKYQ_AGENT_HOOK_VERSION) [ -z "${ZKYQ_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    ZKYQ_PANE_KEY) [ -z "${ZKYQ_PANE_KEY:-}" ] || return 0 ;;',
    '    ZKYQ_TAB_ID) [ -z "${ZKYQ_TAB_ID:-}" ] || return 0 ;;',
    '    ZKYQ_WORKTREE_ID) [ -z "${ZKYQ_WORKTREE_ID:-}" ] || return 0 ;;',
    '    ZKYQ_AGENT_LAUNCH_TOKEN) [ -z "${ZKYQ_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __orca_value=$(__orca_read_ancestor_var "$__orca_name") || { [ "$?" != 2 ] || zkyq_recovery_conflict=1; return 0; }',
    '  [ -n "$__orca_value" ] && export "$__orca_name=$__orca_value"',
    '}',
    '__orca_endpoint_value() {',
    '  __orca_endpoint_name="$1"',
    '  __orca_endpoint_path="$2"',
    '  __orca_value=$(sed -n -E "s/^(set )?(${__orca_endpoint_name}|ORCA_${__orca_endpoint_name#ZKYQ_})=//p" "$__orca_endpoint_path" 2>/dev/null | tr -d "\\r" | sort -u)',
    '  case "$__orca_value" in *"\n"*) return 2 ;; esac',
    '  printf "%s\\n" "$__orca_value"',
    '}',
    '__orca_fill_from_endpoint_file() {',
    '  __orca_endpoint_path="$1"',
    '  [ -r "$__orca_endpoint_path" ] || return 0',
    '  __orca_endpoint_port=$(__orca_endpoint_value ZKYQ_AGENT_HOOK_PORT "$__orca_endpoint_path") || { zkyq_recovery_conflict=1; return 0; }',
    '  if [ -n "${ZKYQ_AGENT_HOOK_PORT:-}" ] && [ -n "$__orca_endpoint_port" ] && [ "$__orca_endpoint_port" != "$ZKYQ_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __orca_endpoint_name in ZKYQ_AGENT_HOOK_PORT ZKYQ_AGENT_HOOK_TOKEN ZKYQ_AGENT_HOOK_ENV ZKYQ_AGENT_HOOK_VERSION; do',
    '    eval "__orca_current=\\${$__orca_endpoint_name:-}"',
    '    [ -z "$__orca_current" ] || continue',
    '    __orca_endpoint_value=$(__orca_endpoint_value "$__orca_endpoint_name" "$__orca_endpoint_path") || { zkyq_recovery_conflict=1; return 0; }',
    '    [ -n "$__orca_endpoint_value" ] && export "$__orca_endpoint_name=$__orca_endpoint_value"',
    '  done',
    '}',
    '# Why: Command Code sanitizes hook subprocess env. The parent TUI process',
    '# still has Orca pane/hook metadata, so recover it before posting.',
    'for __orca_name in ZKYQ_AGENT_HOOK_ENDPOINT ZKYQ_AGENT_HOOK_PORT ZKYQ_AGENT_HOOK_TOKEN ZKYQ_AGENT_HOOK_ENV ZKYQ_AGENT_HOOK_VERSION ZKYQ_PANE_KEY ZKYQ_TAB_ID ZKYQ_WORKTREE_ID ZKYQ_AGENT_LAUNCH_TOKEN; do',
    '  __orca_fill_from_ancestor "$__orca_name"',
    'done',
    'if [ -n "$ZKYQ_AGENT_HOOK_ENDPOINT" ] && [ -r "$ZKYQ_AGENT_HOOK_ENDPOINT" ]; then',
    '  __orca_fill_from_endpoint_file "$ZKYQ_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Why: Command Code strips TOKEN-like env vars before invoking hooks. If',
    '# ZKYQ_AGENT_HOOK_ENDPOINT was not exported into this PTY, recover the',
    '# matching endpoint file by the unstripped loopback port.',
    'if [ -z "$ZKYQ_AGENT_HOOK_TOKEN" ] && [ -n "$ZKYQ_AGENT_HOOK_PORT" ]; then',
    '  if [ -n "${ZKYQ_USER_DATA_PATH:-}" ]; then',
    '    for endpoint in "$ZKYQ_USER_DATA_PATH/agent-hooks/endpoint-v2.env" "$ZKYQ_USER_DATA_PATH/agent-hooks"/*/endpoint-v2.env; do __orca_fill_from_endpoint_file "$endpoint"; done',
    '  fi',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks"/*/endpoint-v2.env \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks/endpoint-v2.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks"/*/endpoint-v2.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks/endpoint-v2.env" \\',
    '    "$HOME/Library/Application Support/orca/agent-hooks/endpoint-v2.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca/agent-hooks/endpoint-v2.env" \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/orca/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(__orca_endpoint_value ZKYQ_AGENT_HOOK_PORT "$endpoint") || { zkyq_recovery_conflict=1; continue; }',
    '    if [ "$endpoint_port" = "$ZKYQ_AGENT_HOOK_PORT" ]; then',
    '      __orca_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -n "${zkyq_recovery_conflict:-}" ]; then unset ZKYQ_PANE_KEY; fi',
    'zkyq_hook_namespace=Zkyq',
    'if [ "${ZKYQ_AGENT_HOOK_VERSION:-}" = 1 ]; then zkyq_hook_namespace=Orca; fi',
    'if [ -z "$ZKYQ_AGENT_HOOK_PORT" ] || [ -z "$ZKYQ_AGENT_HOOK_TOKEN" ] || [ -z "$ZKYQ_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Timeout caps best-effort hook posts if the local listener stalls.
    // Why: pipe payload to curl's stdin (`payload@-`) instead of an inline
    // `payload=$VALUE` arg, so tens-of-KB tool output stays off the curl
    // command line (EDR command-line false positives). Wire body is identical.
    'printf \'%s\' "$payload" | curl -sS -X POST "http://127.0.0.1:${ZKYQ_AGENT_HOOK_PORT}/hook/command-code" \\',
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-${zkyq_hook_namespace}-Agent-Hook-Token: ${ZKYQ_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${ZKYQ_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${ZKYQ_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${ZKYQ_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${ZKYQ_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${ZKYQ_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${ZKYQ_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
